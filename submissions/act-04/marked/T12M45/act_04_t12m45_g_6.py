def Ay(wL, wR, L):
    return L* (wR - 2*wL) / 6

def By(wL, wR, L):
    return L* (2* wR - wL) / 6

def polyvalder(a, s):
      p = 0
      dp = 0

      for c in reversed (a):
          dp = dp * s + p
          p = p * s + c

      return np.array([p, dp])

def nu(x, wL, wR, L):
    a0 = Ay(wL, wR, L)
    a1 = wL
    a2 = -(wL + wR) / (2.0 * L)
    return polyvalder([a0, a1, a2], x)

def mu(x, wL, wR, L):
    a0 = 0.0
    a1 = Ay(wL, wR, L)
    a2 = wL / 2.0
    a3 = -(wL + wR) / (6.0 * L)
    return polyvalder([a0, a1, a2, a3], x)

def m(x, wL, wR, L):
    a0 = -(L**3 / 360.0) * (7.0 * wL - 3.0 * wR)
    a1 = 0.0
    a2 = Ay(wL, wR, L) / 2.0
    a3 = wL / 6.0
    a4 = -(wL + wR) / (24.0 * L)
    return polyvalder([a0, a1, a2, a3, a4], x)

def y(x, wL, wR, L):
    a0 = 0.0
    a1 = -(L**3 / 360.0) * (7.0 * wL - 3.0 * wR)
    a2 = 0.0
